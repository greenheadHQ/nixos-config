CARD_QUALITY = """카드 품질(쓰기 전 확인, 앞 항목 우선)
1. 채점 기준 하나: 노트 하나는 기억할 것 하나를 묻는다. 두 번째 기준·목록·긴 코드가 보이면 노트를 나누고 링크하며, 부분 사이의 관계가 중요하면 관계를 묻는 카드를 하나 둔다. 여러 개를 한 번에 채점하면 어디서 틀렸는지 알 수 없다.
2. 답이 하나로 정해지게: 질문만 읽어도 답의 종류와 범위(이름 하나, 이유 한 문장, 코드 한 줄)를 알 수 있게 쓴다. 버전·환경·전제 같은 조건과 사용 장면은 질문 문장 안에 쓴다.
3. 떠올려야 풀리게: 답을 가리고, 모르는 사람이 질문과 맥락 줄만으로 답할 수 있으면 다시 쓴다. 답의 단어·어근, 예/아니오, 둘 중 고르기, 답 자리 바로 뒤 조사가 흔한 단서다.
4. 맥락 줄은 개념 경로: "분야 > 상위 개념 > 개념"으로 쓰고, 끝 마디가 답이면 한 단계 위에서 멈춘다. 어느 강의·책·대화에서 배웠는지는 맥락 줄에 쓰지 않는다. 순번·단계 번호·N번째 같은 서수·개수·총계처럼 덱 구성이 바뀌면 틀리는 표현은 카드 어디에도 쓰지 않고, 버전·연도·내용 속 수치는 쓴다.
5. 쓰일 장면: 핵심 개념은 정의 카드와 함께 실제 상황에서 판단·예측하게 하는 카드를 둔다. 정의 연습만으로는 적용이 늘지 않는다.
6. 펼침 영역은 채점 기준만: 답은 한 줄 또는 한 문장이고, 질문 쪽 코드는 폰 한 화면 안에 둔다. 이유·예시·관련 노트 설명은 "암기 제외"로 접는다. 출처 칸에는 참고 문헌(제목·링크·장/절/쪽, 필요하면 판본·버전)만 쓰고, 수정 전후·검증 과정·확인일·한계는 대화로 보고한다.
7. 수정은 다시 쓰기: 기존 회상 목표와 새 요청을 함께 만족하는 판을 새로 쓰고, 요청받지 않은 추가는 제안으로 말한다. 앞선 결정과 부딪히면 사용자에게 묻고, 관점이 번갈아 요구되면 카드 나누기를 먼저 권한다."""

REQUIRED_RULES = """필수 규칙
- 사용자가 대화에서 배운 내용을 카드로 만들거나 학습 내용을 보완할 때 적용한다. 세션 시작부터 카드 작성을 전제하지 않는다. 단순 조회·그대로 옮기기·오타/서식 수정에는 이해 확인이나 전체 제작 절차를 강요하지 않는다.
- 개념 관계는 조회로 확인한 note ID를 대상으로 삼고 `[표시 제목|nid<13자리 note ID>]` 형식으로 저장한다. raw anki:// URL이나 이를 감싼 HTML 링크를 필드에 저장하지 않는다.
- 대화 자체는 출처가 아니다. 원문 없이 대화로 배운 내용은 대조한 공식 문서·표준만 쓰고, 대조한 자료가 없으면 비운다.
- 개인 자료의 본문·인증 정보를 외부 검색 URL에 넣지 않고, Mac 로컬 경로를 iPhone에서 열 수 있는 출처로 제시하지 않는다.
- 새 태그를 만들어 붙이지 않는다. 사용자가 요청한 태그만 붙이고, 기존 태그는 요청 없이 지우거나 바꾸지 않는다."""

AUTHORING_GUIDANCE = """카드 작성 원칙
- 이해: 지금까지 사용자가 직접 설명·예측·적용한 내용을 활용한다. 이미 이해를 보여 줬다면 다시 시험하지 않는다.
  이해가 아직 관찰되지 않은 것과 오개념이 드러난 것을 구분한다. 핵심 확인이 필요하면 배운 범위의 짧은 응용 질문을 하나씩 묻고 답을 기다린다.
  출제·교정 전에 정답과 적용 조건의 근거를 확인한다. 막히면 힌트·선택지·예시와 정확한 피드백으로 돕는다.
  중요한 공백이 남으면 설명 보완·범위 축소·해당 후보 보류를 권한다. 완전 이해, 점수 합격선, 매 카드 의무시험은 요구하지 않으며 퀴즈를 원하지 않는 선택을 존중한다.
- 가치: 현재 학습 목표와 사용자 관심, 이후 이해의 기반, 반복 혼동, 실제 사용할 상황을 기준으로 외울 내용을 선별한다.
  찾으면 되는 세부사항과 지엽적 예외는 참고로 남길 수 있다. 당장 쓰지 않는 기초 원리를 버리거나 AI가 덧붙인 지식을 자동으로 암송 범위에 넣지 않는다.
- 근거: 질문의 전제·답·설명·관계의 핵심 주장을 실제로 읽은 원문과 대조한다. 해당 판본/버전/환경을 맞추고 직접 근거와 추론을 구분한다.
  대화 중 AI 답변, 기존 카드, URL 존재, 모델들의 동의만으로 검증 완료라고 하지 않는다. 원문에 접근하지 못했으면 그 한계를 대화로 밝힌다.
  불확실한 부연은 빼고, 핵심 주장이 미해결이면 암기용 반영을 보류한다. 이 서버는 웹 검색이나 개인 책 원문 조회 도구를 제공하지 않는다.
- 기존 지식: anki_find_notes로 용어·동의어·관련 개념을 검색하고, anki_note_info로 후보의 전체 내용을 확인해 중복과 관계를 판단한다.
  일부 페이지/잘린 본문만 보고 전수 확인했다고 하지 않는다. 회상 목표가 같으면 기존 노트를 다시 쓰고, 다르면 새 노트로 만든다.
  의미 있는 관련 노트가 있으면 선수 개념·대조·같은 원리의 적용 등 관계와 이유를 한 줄로 적고 하이퍼링크를 반드시 붙인다. 적합한 대상이 없으면 억지 연결이나 연결용 카드를 만들지 않는다.
- 연결: 링크할 note ID를 추측하지 않는다. 표시 제목은 의미 있는 일반 텍스트로 쓰고 `[`는 `\\[`로 이스케이프한다.
  card ID는 사용자가 복사한 특정 카드의 출제 형태를 찾는 포인터로만 쓰며 Note Linker 문법에 넣지 않는다.
  Desktop에서는 활성 Anki Note Linker가 내부 미리보기를 열고, iPhone에서는 카드 템플릿 adapter가 AnkiMobile 탐색 검색을 연다.
  anki_model_info로 링크를 넣을 필드에 mobile renderer가 적용됐는지 확인한다. 미적용이면 플랫폼별 URL로 우회하지 말고 템플릿 준비 필요를 보고한다.
  관계 설명과 링크는 뒷면 링크 지원 필드(관리 유형은 설명)의 "암기 제외" 접힌 영역에 둔다. 접지 않으면 펼침 영역에 보인다. iPhone의 도착점은 즉시 복습이나 팝업이 아니라 탐색 검색이다.
  삭제·재생성·가져오기 후에는 대상을 재확인한다. 역링크를 위해 기존 노트를 자동으로 연쇄 수정하지 않는다.
- 코드: 독립 코드 예제는 `<pre><code class="language-javascript">…</code></pre>`처럼 저장하고 실제 언어를 명시한다.
  지원 표시는 javascript/js/jsx, typescript/ts/tsx, html/xml, css, json, bash/sh/shell, sql, c, python/py, java, yaml/yml, http다.
  도식·출력·자연어는 language-plaintext로 둔다. 언어를 알 수 없으면 추측해 지정하지 않는다. 미지정·미지원 언어는 단색이다.
  코드 원문의 &, <, >를 HTML text로 이스케이프하고 들여쓰기·개행을 보존한다. 구문 색칠용 span·인라인 색상·자동 줄바꿈 style은 저장하지 않는다.
  문장 안 식별자는 일반 <code>를 유지한다. Markdown fence를 HTML 대신 저장하지 않는다.
  anki_model_info에서 코드 강조 renderer 적용 여부를 확인한다. 미적용 유형과 구형 Markdown/Cloze 유형을 자동 교체하지 않는다.
- 출처: 실제로 읽고 대조한 자료를 빠뜨리지 않고 제목·URL 또는 서지정보·장/절/쪽/그림 위치로 남기며, 필요하면 판본·버전을 붙인다.
  관련 문헌을 무한 수집하거나 참고문헌을 암송하도록 요구하지 않는다.
- 태그: 주제는 덱과 맥락 줄이, 상태는 카드 정지 상태가 이미 담고, 순서·날짜는 태그로 남기지 않는다.
  mcp::added는 서버가 붙이고 marked는 사용자의 검토 대기열이다.
- 반영: anki_models/anki_model_info로 현재 필드와 표시 위치를 확인해 기존 필드에 구성한다. 출처의 참고 자료는 보존하고, 배치 번호·원본 노트 ID 같은 식별 줄은 그 노트를 고칠 때 지운다.
  기존 note/card ID와 학습 기록을 유지하고, 수정 전후·근거·영향은 대화로 보고한다. 이미 적힌 작업 기록(수정 전후·검증 과정)은 그대로 두고 새로 덧붙이지 않는다.
  단순 링크를 위해 노트 유형을 바꾸거나 학습 일정·배치 활성화·원본 카드 정지 상태를 변경하지 않는다. 기존 카드 수정은 같은 회상 목표인지 확인한다.
  승인된 작성 범위 안에서 처리하고 불필요한 재승인을 요구하지 않는다. 변경 뒤 anki_note_info로 답·출처·링크를 재조회하고 적용·동기화·기기 확인을 구분해 보고한다.
  작성·검증은 최초 쓰기 전에 한다. 재시도에서는 원래 본문과 request_id를 그대로 유지하며, 영수증의 partial/unknown을 새 카드 작성 요청처럼 반복하지 않는다.
"""


def compose_guidance(tool_text: str = "") -> str:
    """Card quality, required rules, a writing tool's own text if given, then the remaining principles."""
    # Claude clients passed only the first 2,048 description characters (#1440); tests keep the required text there.
    blocks = [CARD_QUALITY, REQUIRED_RULES, tool_text, AUTHORING_GUIDANCE]
    return "\n\n".join(block for block in blocks if block)
