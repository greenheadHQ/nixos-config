"""Merge only the two non-sensitive 1Password shortcuts into its mutable settings."""

import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile

APP_RUNNING_MESSAGE = "deferred while 1Password is running; quit it and run onepassword-shortcuts"


def is_app_running():
    result = subprocess.run(
        ["/usr/bin/pgrep", "-U", str(os.getuid()), "-x", "1Password"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    if result.returncode not in (0, 1):
        raise RuntimeError("could not determine whether 1Password is running")
    return result.returncode == 0


def apply_shortcuts(path, desired):
    try:
        info = path.lstat()
    except FileNotFoundError:
        return "settings absent; open and set up 1Password, then run onepassword-shortcuts"
    if not stat.S_ISREG(info.st_mode):
        raise ValueError("settings must be a regular file, not a symlink")

    original = path.read_bytes()
    settings = json.loads(original)
    if not isinstance(settings, dict):
        raise ValueError("settings must contain a JSON object")
    if all(settings.get(key) == value for key, value in desired.items()):
        return "already configured"
    # An open app can overwrite external changes with its in-memory settings.
    # Do not quit it during nrs: it also supplies the user's SSH agent.
    if is_app_running():
        return APP_RUNNING_MESSAGE

    settings.update(desired)
    fd, temporary = tempfile.mkstemp(prefix=".nix-shortcuts-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            os.fchmod(stream.fileno(), stat.S_IMODE(info.st_mode))
            json.dump(settings, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        if is_app_running():
            return APP_RUNNING_MESSAGE
        # Best-effort detection, not compare-and-swap: keep the app closed and
        # do not edit this file with another tool while the helper is running.
        if path.read_bytes() != original:
            raise RuntimeError("settings changed during apply; retry after closing 1Password")
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return "applied; reopen 1Password to use the new shortcuts"


def main():
    if len(sys.argv) != 4:
        print("usage: apply-shortcuts.py SETTINGS QUICK_ACCESS AUTOFILL", file=sys.stderr)
        return 1
    try:
        message = apply_shortcuts(
            Path(sys.argv[1]),
            {"keybinds.quickAccess": sys.argv[2], "keybinds.autoFill": sys.argv[3]},
        )
    except (OSError, ValueError, RuntimeError):
        # Do not print the settings payload, which also holds account/security data.
        print(
            "1Password shortcuts: settings unavailable or invalid; no shortcuts applied. "
            "Check app-data access and retry with 1Password closed.",
            file=sys.stderr,
        )
        return 1
    print(f"1Password shortcuts: {message}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
